export function inferCountryFromScenario(scenario = {}) {
  const text = [scenario.direction, scenario.title, scenario.shortTitle].filter(Boolean).join(' ').toLowerCase();
  if (text.includes('турц')) return 'Турция';
  if (text.includes('егип')) return 'Египет';
  if (text.includes('таил')) return 'Таиланд';
  if (text.includes('оаэ') || text.includes('дуба')) return 'ОАЭ';
  return defaultProfile.country;
}

export function getTravelRequirementProfile(country) {
  return countryRequirementProfiles[country] || defaultProfile;
}

export function buildTravelDocumentChecklist(scenario = {}) {
  const country = inferCountryFromScenario(scenario);
  const profile = getTravelRequirementProfile(country);
  const hasChildren = Boolean(scenario.clientProfile?.children?.length);
  const clientContext = [
    scenario.clientProfile?.family,
    hasChildren ? `дети: ${scenario.clientProfile.children.join(', ')}` : '',
    scenario.clientProfile?.budget
  ].filter(Boolean).join(' · ');

  return {
    country: profile.country,
    passportCountry: profile.defaultPassport,
    clientContext,
    summary: profile.summary,
    warning: profile.warning,
    questions: profile.countrySpecificQuestions,
    checks: profile.requiredChecks.map((text, index) => ({
      id: `${profile.country}-${index + 1}`.replace(/\s+/g, '-'),
      text
    })),
    sourceNotes: profile.sourceNotes,
    sourcePolicy: 'Ежедневная авто-проверка источников будет подключена после загрузки URL базы/памятки. До этого менеджер обязан вручную открыть официальный источник перед оплатой.'
  };
}
